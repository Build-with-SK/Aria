def save_signals(signals: Dict[str, dict], run_date: Optional[str] = None) -> int:
    """
    Save all signals to signals_history table.
    Returns number of rows inserted.
    """
    today = run_date or str(date.today())
    rows = []

    for ticker, sig in signals.items():
        rows.append((
            today,
            ticker,
            sig.get("asset_class"),
            sig.get("current_price"),
            sig.get("composite_score"),
            sig.get("action"),
            sig.get("confidence"),
            sig.get("bullish_prob"),
            sig.get("bearish_prob"),
            sig.get("trend_score"),
            sig.get("momentum_score"),
            sig.get("volatility_score"),
            sig.get("regime_score"),
            sig.get("macro_score"),
            sig.get("sentiment_score"),
            sig.get("risk_level"),
            sig.get("realised_vol"),
            sig.get("stop_loss"),
            sig.get("take_profit"),
            sig.get("position_size_pct"),
            sig.get("regime"),
            sig.get("explanation", ""),
        ))

    with get_connection() as conn:
        conn.executemany("""
            INSERT INTO signals_history (
                run_date, ticker, asset_class, current_price, composite_score,
                action, confidence, bullish_prob, bearish_prob,
                trend_score, momentum_score, volatility_score, regime_score,
                macro_score, sentiment_score, risk_level, realised_vol,
                stop_loss, take_profit, position_size_pct, regime, explanation
            ) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)
        """, rows)

    logger.info(f"Saved {len(rows)} signals to database for {today}")
    return len(rows)


def save_prices(raw_data: Dict[str, Any], run_date: Optional[str] = None) -> int:
    """Save latest OHLCV prices for all assets."""
    today = run_date or str(date.today())
    rows = []

    for ticker, df in raw_data.items():
        if df is None or df.empty:
            continue
        try:
            last = df.iloc[-1]
            rows.append((
                today, ticker,
                float(last.get("Open",  last.get("open",  0))),
                float(last.get("High",  last.get("high",  0))),
                float(last.get("Low",   last.get("low",   0))),
                float(last.get("Close", last.get("close", 0))),
                float(last.get("Volume", last.get("volume", 0)) or 0),
            ))
        except Exception:
            continue

    with get_connection() as conn:
        conn.executemany("""
            INSERT OR REPLACE INTO price_history
            (run_date, ticker, open_price, high_price, low_price, close_price, volume)
            VALUES (?,?,?,?,?,?,?)
        """, rows)

    logger.info(f"Saved {len(rows)} price rows to database for {today}")
    return len(rows)


