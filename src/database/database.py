def get_best_performing_signals(min_score: float = 40, days: int = 90) -> pd.DataFrame:
    """
    Get signals with score > threshold and check subsequent price performance.
    Used to validate: do high-score Buy signals actually go up?
    """
    with get_connection() as conn:
        df = pd.read_sql_query("""
            SELECT s.run_date, s.ticker, s.action, s.composite_score,
                   s.current_price, s.confidence,
                   p.return_1d, p.return_5d, p.return_20d,
                   p.signal_correct_1d, p.signal_correct_5d, p.signal_correct_20d
            FROM signals_history s
            LEFT JOIN signal_performance p
                ON s.ticker = p.ticker AND s.run_date = p.signal_date
            WHERE s.composite_score >= ?
            ORDER BY s.run_date DESC
            LIMIT 100
        """, conn, params=(min_score,))
    return df


def get_database_stats() -> dict:
    """Return stats about what's stored in the database."""
    with get_connection() as conn:
        stats = {}
        for table in ["signals_history", "price_history", "alerts_history",
                      "macro_history", "ml_predictions_history", "backtest_history"]:
            try:
                count = conn.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]
                stats[table] = count
            except Exception:
                stats[table] = 0

        # Date range of signals
        try:
            row = conn.execute(
                "SELECT MIN(run_date), MAX(run_date) FROM signals_history"
            ).fetchone()
            stats["signals_date_range"] = {"from": row[0], "to": row[1]}
        except Exception:
            stats["signals_date_range"] = {}

    return stats


def update_signal_performance(raw_data: Dict[str, Any], run_date: Optional[str] = None) -> None:
    """
    Update signal_performance table with actual future prices.
    Run this daily to see how last week's signals performed.

    For each signal from 1, 5, 20 days ago, record the actual price
    and compute whether the signal direction was correct.
    """
    today = run_date or str(date.today())

    with get_connection() as conn:
        # Get signals from the past that need price updates
        pending = pd.read_sql_query("""
            SELECT DISTINCT s.ticker, s.run_date, s.composite_score,
                            s.action, s.current_price
            FROM signals_history s
            LEFT JOIN signal_performance p
                ON s.ticker = p.ticker AND s.run_date = p.signal_date
            WHERE p.id IS NULL
              AND s.run_date >= date(?, '-25 days')
        """, conn, params=(today,))

    if pending.empty:
        return

    for _, row in pending.iterrows():
        ticker     = row["ticker"]
        sig_date   = row["run_date"]
        entry_px   = row["current_price"]
        score      = row["composite_score"]

        if ticker not in raw_data or raw_data[ticker] is None:
            continue

        try:
            close = raw_data[ticker]["Close"].squeeze()
            # Find the signal date in the price index
            close.index = pd.to_datetime(close.index)
            sig_dt = pd.to_datetime(sig_date)

            future_prices = close[close.index > sig_dt]
            if future_prices.empty:
                continue

            def _get_return(n_days):
                if len(future_prices) >= n_days:
                    px = float(future_prices.iloc[n_days - 1])
                    ret = (px / entry_px - 1) if entry_px else None
                    correct = 1 if (score > 0 and ret > 0) or (score < 0 and ret < 0) else 0
                    return px, ret, correct
                return None, None, None

            px1,  r1,  c1  = _get_return(1)
            px5,  r5,  c5  = _get_return(5)
            px20, r20, c20 = _get_return(20)

            with get_connection() as conn:
                conn.execute("""
                    INSERT OR REPLACE INTO signal_performance
                    (signal_date, ticker, action, composite_score, entry_price,
                     price_1d, price_5d, price_20d,
                     return_1d, return_5d, return_20d,
                     signal_correct_1d, signal_correct_5d, signal_correct_20d)
                    VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)
                """, (
                    sig_date, ticker, row["action"], score, entry_px,
                    px1, px5, px20, r1, r5, r20, c1, c5, c20,
                ))
        except Exception as e:
            logger.debug(f"Performance update failed for {ticker}: {e}")

    logger.info(f"Updated signal performance for {len(pending)} signals")
