"""
database.py
===========
Phase 4 — SQLite database layer.

Stores all historical data locally so you can:
  - Track how signals performed over time
  - See if Buy signals actually led to gains
  - Query "what was the signal for AAPL on 2025-03-15?"
  - Build a track record of the system's predictions
  - Run signal performance analytics

Tables:
  signals_history   — every signal generated, every day
  price_history     — daily OHLCV for all assets
  backtest_history  — backtest results per run
  alerts_history    — all alerts ever fired
  macro_history     — daily macro snapshots
  ml_predictions_history — ML predictions per day

Uses SQLite — no server needed, zero config, file-based.
Database file: data/trading_intelligence.db

All writes are append-only. Never deletes historical data.
"""

from __future__ import annotations

import json
import logging
import sqlite3
from contextlib import contextmanager
from datetime import date, datetime
from pathlib import Path
from typing import Dict, List, Optional, Any

import pandas as pd

logger = logging.getLogger(__name__)

DB_PATH = Path("data/trading_intelligence.db")


# ===========================================================================
# Connection manager
# ===========================================================================

@contextmanager
def get_connection():
    """Context manager for SQLite connections. Auto-commits and closes."""
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(str(DB_PATH), timeout=30)
    conn.row_factory = sqlite3.Row   # Enables dict-like access to rows
    conn.execute("PRAGMA journal_mode=WAL")   # Better concurrent access
    conn.execute("PRAGMA foreign_keys=ON")
    try:
        yield conn
        conn.commit()
    except Exception as e:
        conn.rollback()
        raise e
    finally:
        conn.close()


